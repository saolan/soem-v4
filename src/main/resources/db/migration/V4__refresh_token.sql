/*==============================================================================
  V4 - REFRESH_TOKEN
  ------------------------------------------------------------------------------
  El esquema base no tiene ninguna tabla de sesion/refresh token. Se crea para
  soportar rotacion (cada renovacion invalida el token anterior y encadena el
  nuevo via TOKEN_PADRE_ID) y deteccion de reuso (un TOKEN_HASH que ya fue
  marcado REVOCADO indica un posible robo: se revocan todos los tokens
  vigentes de esa persona).

  Nunca se persiste el token en claro: TOKEN_HASH guarda SHA-256(valor
  crudo); el valor crudo solo viaja en la cookie HttpOnly de la respuesta.

  Sin columnas de auditoria (USUARI_REGI/MODI): su semantica propia
  (FECHA_HORA_EMISION, REVOCADO, FECHA_HORA_REVOCADO) es mas precisa aqui que
  los campos genericos de EntidadAuditable, y al no tener FECHA_HORA_MODI no
  queda alcanzada por el trigger trg_marca_modificacion (correcto: no
  queremos que el rol tecnico del pool de conexion pise campos que la propia
  aplicacion controla explicitamente).
==============================================================================*/

CREATE TABLE refresh_token (
   refresh_token_id     INT4 GENERATED BY DEFAULT AS IDENTITY not null,
   persona_id           INT4                                  not null,
   sucursal_id          INT4                                  null,
   token_padre_id       INT4                                  null,
   token_hash           VARCHAR(255)                          not null,
   fecha_hora_emision   TIMESTAMP WITH TIME ZONE              not null default now(),
   fecha_hora_expira    TIMESTAMP WITH TIME ZONE              not null,
   revocado             BOOL                                  not null default false,
   fecha_hora_revocado  TIMESTAMP WITH TIME ZONE              null,
   motivo_revocacion    VARCHAR(30)                           null,
   ip_origen            VARCHAR(45)                           null,
   agente_usuario       VARCHAR(255)                          null,
   constraint PK_REFRESH_TOKEN primary key (refresh_token_id),
   constraint UQ_REFRESH_TOKEN_HASH unique (token_hash),
   constraint CK_REFRESH_TOKEN_MOTIVO check (motivo_revocacion is null or motivo_revocacion in ('rotacion', 'logout', 'reuso_detectado'))
);

ALTER TABLE refresh_token
   ADD CONSTRAINT FK_PERSUSUA_REFRESHTOKEN FOREIGN KEY (persona_id)
      REFERENCES pers_usua (persona_id)
      ON DELETE RESTRICT ON UPDATE RESTRICT;

ALTER TABLE refresh_token
   ADD CONSTRAINT FK_SUCURSAL_REFRESHTOKEN FOREIGN KEY (sucursal_id)
      REFERENCES sucursal (sucursal_id)
      ON DELETE RESTRICT ON UPDATE RESTRICT;

ALTER TABLE refresh_token
   ADD CONSTRAINT FK_REFRESHTOKEN_REFRESHTOKEN FOREIGN KEY (token_padre_id)
      REFERENCES refresh_token (refresh_token_id)
      ON DELETE RESTRICT ON UPDATE RESTRICT;

CREATE INDEX ix_refresh_token_persona ON refresh_token (persona_id);
CREATE INDEX ix_refresh_token_vigencia ON refresh_token (revocado, fecha_hora_expira);
CREATE INDEX ix_refresh_token_padre ON refresh_token (token_padre_id);

COMMENT ON COLUMN refresh_token.token_hash IS 'SHA-256 del token crudo. El valor crudo nunca se persiste, solo viaja en la cookie HttpOnly del cliente.';
COMMENT ON COLUMN refresh_token.token_padre_id IS 'Token del que este es la rotacion. Nulo en el primer token de la cadena (login).';
COMMENT ON COLUMN refresh_token.sucursal_id IS 'Sucursal activa de la sesion en el momento de emitir este token, para preservar el contexto elegido en el login a traves de las rotaciones.';
