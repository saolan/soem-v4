/*==============================================================================
  TRIGGERS DE AUDITORIA
  ------------------------------------------------------------------------------
  Mantienen USUARI_MODI y FECHA_HORA_MODI, y protegen USUARI_REGI y
  FECHA_HORA_REGI de ser sobrescritos. Sin ellos, esas cuatro columnas quedan a
  cargo de la aplicacion y se desincronizan.
  La funcion se crea SIN calificar: queda en el esquema activo, de modo que cada
  esquema es una unidad completa y autocontenida.
==============================================================================*/

CREATE OR REPLACE FUNCTION trg_marca_modificacion() RETURNS trigger AS $tg$
BEGIN
  NEW.usuari_modi     := current_user;
  NEW.fecha_hora_modi := now();
  NEW.usuari_regi     := OLD.usuari_regi;       -- inmutables
  NEW.fecha_hora_regi := OLD.fecha_hora_regi;
  RETURN NEW;
END; $tg$ LANGUAGE plpgsql;

DO $trg$
DECLARE r record; n int := 0;
BEGIN
  FOR r IN
    SELECT c.relname AS tabla
    FROM pg_class c
    JOIN pg_namespace ns ON ns.oid = c.relnamespace
    WHERE ns.nspname = current_schema() AND c.relkind = 'r'
      AND EXISTS (SELECT 1 FROM pg_attribute a
                  WHERE a.attrelid = c.oid AND a.attname = 'fecha_hora_modi'
                    AND a.attnum > 0 AND NOT a.attisdropped)
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON %I', r.tabla||'_marca_modi', r.tabla);
    EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON %I
                      FOR EACH ROW EXECUTE FUNCTION trg_marca_modificacion()',
                   r.tabla||'_marca_modi', r.tabla);
    n := n + 1;
  END LOOP;
  RAISE NOTICE 'Triggers de auditoria creados: %', n;
END $trg$;


