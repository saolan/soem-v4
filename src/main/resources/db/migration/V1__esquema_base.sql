/*==============================================================================
  soemPostgres 3.1  -  ESQUEMA COMPLETO PARA BASE DE DATOS NUEVA
  Destino: PostgreSQL 17
  ------------------------------------------------------------------------------
  Cambios respecto del DDL 3.0 original:
    - Se eliminan los 19 DOMAIN (no los usaba ninguna tabla).
    - Los enteros se mantienen en INT4 (ver nota al pie).
    - Claves primarias subrogadas con GENERATED BY DEFAULT AS IDENTITY
      (84 tablas). Las 13 tablas de especializacion cuya PK es tambien FK
      conservan la PK heredada, sin identity.
    - Fechas con hora en TIMESTAMP WITH TIME ZONE. AUDITORIA.DIRECC_IP en INET.
    - Columnas de auditoria (USUARI_REGI, FECHA_HORA_REGI, USUARI_MODI,
      FECHA_HORA_MODI) en 41 tablas transaccionales.
    - Columnas FECHA renombradas a FECHA_REGI en CAJA_MOVI, FORM_PAGO_MOVI_EGRE,
      FORM_PAGO_MOVI_INGR y FPME_FORM_PAGO.
    - Indices sobre las claves foraneas y restricciones UNIQUE / CHECK.
    - La vista kard_tota_view se reproduce SIN CAMBIOS.

  NOTA 1: AUDITORIA conserva la columna FECHA segun el DDL indicado
  explicitamente. Si tambien debe renombrarse a FECHA_REGI, cambiarlo aca
  y en el script de migracion.

  NOTA 2 - POR QUE INT4 Y NO BIGINT:
  Con los volumenes reales de estas instalaciones (la mayor: 25.000 productos,
  510.000 precios, 206.000 comprobantes, 1.186.671 movimientos de kardex) el
  limite de 2.147 millones de INT4 es inalcanzable: al ritmo de crecimiento
  actual tomaria siglos. Mediciones sobre 1.000.000 de filas con 7 columnas
  *_id:
      tabla  INT4 ....  81 MB      BIGINT .. 104 MB   (+28 %)
      indice INT4 .... 6952 kB     BIGINT .. 6952 kB  (identico: las entradas
                                   de indice se alinean a 8 bytes igual)
      consulta agregada sobre indice: 4,7 ms vs 4,8 ms  (sin diferencia)
      conversion de tipo: 5,7 s por millon de filas
  BIGINT solo tendria sentido si se consolidaran varias instalaciones en una
  sola base o se asignaran rangos de ID por sucursal, cosa que no ocurre.

  COMO EJECUTARLO
  ------------------------------------------------------------------------------
  SQL puro, sin meta-comandos de psql. Corre en pgAdmin4 y en consola Linux.

  A) Consola Linux:
       createdb -h SERVIDOR -U USUARIO soem
       psql -h SERVIDOR -U USUARIO -d soem -v ON_ERROR_STOP=1 -1 -f este_archivo.sql

  B) pgAdmin4: crear la base, abrir el Query Tool sobre ella y ejecutar el
     archivo completo.
	 
  C) CREATE SCHEMA cliente_001;
     SET search_path = cliente_001, public;
     -- ejecutar soem_3_1_nueva_bd.sql
==============================================================================*/

