-- Sin calificar con 'public.': la vista debe crearse en el esquema activo.
-- Calificada, todos los esquemas compartirian UNA sola vista en public, y el
-- ultimo en ejecutarse la reapuntaria a sus propias tablas.
CREATE OR REPLACE VIEW kard_tota_view AS 
 SELECT s.sucursal_id,
    s.descri AS sucu_descri,
    b.bodega_id,
    b.descri AS bode_descri,
    p.producto_id,
    p.descri AS prod_descri,
    COALESCE(sum(id.cantid * id.factor * d.factor::numeric), 0::numeric) AS cantid_ingr,
    COALESCE(sum(id.cantid * id.factor * id.costo_neto / id.factor * d.factor::numeric), 0::numeric) AS total_ingr,
    COALESCE(sum(ed.cantid * ed.factor * d.factor::numeric * '-1'::integer::numeric), 0::numeric) AS cantid_egre,
    COALESCE(sum(ed.cantid * ed.factor * ed.costo * d.factor::numeric * '-1'::integer::numeric), 0::numeric) AS total_egre,
    COALESCE(sum(id.cantid * id.factor * d.factor::numeric), 0::numeric) - COALESCE(sum(ed.cantid * ed.factor * d.factor::numeric * '-1'::integer::numeric), 0::numeric) AS cantid_sald,
    COALESCE(sum(id.cantid * id.factor * id.costo_neto / id.factor * d.factor::numeric), 0::numeric) - COALESCE(sum(ed.cantid * ed.factor * ed.costo * d.factor::numeric * '-1'::integer::numeric), 0::numeric) AS total_sald,
        CASE
            WHEN (COALESCE(sum(id.cantid * id.factor * d.factor::numeric), 0::numeric) - COALESCE(sum(ed.cantid * ed.factor * d.factor::numeric * '-1'::integer::numeric), 0::numeric)) = 0::numeric THEN 0::numeric
            ELSE (COALESCE(sum(id.cantid * id.factor * id.costo_neto / id.factor * d.factor::numeric), 0::numeric) - COALESCE(sum(ed.cantid * ed.factor * ed.costo * d.factor::numeric * '-1'::integer::numeric), 0::numeric)) / (COALESCE(sum(id.cantid * id.factor * d.factor::numeric), 0::numeric) - COALESCE(sum(ed.cantid * ed.factor * d.factor::numeric * '-1'::integer::numeric), 0::numeric))
        END AS costo
   FROM kardex k
     JOIN sucursal s ON s.sucursal_id = k.sucursal_id
     JOIN bodega b ON b.bodega_id = k.bodega_id
     JOIN documento d ON d.documento_id = k.documento_id
     JOIN producto p ON k.producto_id = p.producto_id
     LEFT JOIN ingr_deta id ON id.ingr_deta_id = k.ingr_deta_id
     LEFT JOIN egre_deta ed ON ed.egre_deta_id = k.egre_deta_id
  WHERE d.factor <> 0
  GROUP BY s.sucursal_id, b.bodega_id, p.producto_id
  ORDER BY s.sucursal_id, b.bodega_id, p.producto_id;

ANALYZE;


